def add(category, question, refs, points):
    groups = []
    for doc, section in refs:
        candidates = [c["metadata"]["chunk_id"] for c in chunks
            if c["metadata"]["document_id"] == DOC[doc] and c["metadata"]["section_id"] == "s" + str(section)]
        assert candidates, (doc, section)
        groups.append(candidates)
    rows.append({"id": f"Q{len(rows)+1:02d}", "category": category,
        "answerable": bool(refs), "question": question, "gold_evidence_groups": groups,
        "expected_points": points,
        "grading_rule": "All required points must be conveyed without contradicting the frozen rules or inventing unsupported business conditions; paraphrases accepted."
            if refs else "Must explicitly decline to confirm the requested fact/policy due to insufficient provided material; no invented figures, deadlines or claims of execution. Exact standard refusal is accepted."})


